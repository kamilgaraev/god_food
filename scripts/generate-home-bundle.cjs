const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');

const theme = path.join(__dirname, '..', 'wp-content', 'themes', 'theobroma');
const style = fs.readFileSync(path.join(theme, 'style.css'), 'utf8').replace(/\r\n/g, '\n');
const home = fs.readFileSync(path.join(theme, 'assets/css/home-redesign.css'), 'utf8').replace(/\r\n/g, '\n');
const hash = (value) => crypto.createHash('sha256').update(value).digest('hex');

// The bundle lives beside home-redesign.css; rebase URLs from the theme-root stylesheet.
const rebasedStyle = style.replace(/url\(\s*(['"]?)([^'"\)]+)\1\s*\)/g, (match, quote, url) => {
  if (/^(?:data:|https?:|\/|#)/i.test(url)) return match;
  const rebased = path.posix.relative('assets/css', path.posix.normalize(url));
  return `url(${quote}${rebased}${quote})`;
});

const header = `/* Generated by scripts/generate-home-bundle.cjs. source-sha256 style.css=${hash(style)} home-redesign.css=${hash(home)} */`;
const output = `${header}\n${rebasedStyle}\n${home}\n`;
const dest = path.join(theme, 'assets/css/home-bundle.css');
fs.writeFileSync(dest, output);
console.log(`Wrote ${dest}: ${Buffer.byteLength(output)} bytes, ${zlib.gzipSync(output).length} gzip`);
