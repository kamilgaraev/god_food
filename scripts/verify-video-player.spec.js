const assert = require('node:assert/strict');
const { webkit, chromium } = require('playwright');
const browserType = process.env.BROWSER === 'chromium' ? chromium : webkit;
const baseUrl = process.env.BASE_URL || 'https://theobroma.uit-dev.ru/';

(async () => {
    const browser = await browserType.launch(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : {});
    try {
        const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
        page.setDefaultTimeout(10000);
        await page.goto(baseUrl, { waitUntil: 'domcontentloaded' });
        const consent = page.getByRole('button', { name: 'Понятно', exact: true });
        if (await consent.isVisible()) await consent.click();
        await page.locator('[data-video-collection="reels"] [data-video-open]').first().click();
        const dialog = page.locator('[data-video-player]');
        const viewport = page.locator('[data-player-viewport]');
        const video = () => page.locator('[data-player-slide].is-active video');
        await page.waitForFunction(() => document.querySelector('[data-player-slide].is-active video')?.currentTime > 0);
        await page.waitForFunction(() => document.querySelectorAll('[data-player-slide]')[1]?.classList.contains('has-frame'));
        assert.equal(await page.locator('[data-player-slide] video[poster]').count(), 0, 'Player uses actual first frames instead of arbitrary covers');
        assert.equal(await page.locator('[data-video-progress]').isVisible(), false, 'Reels have no story segments');
        assert.equal(await page.locator('[data-video-pause]').count(), 0, 'No visible pause button');
        assert.equal(await viewport.evaluate(e => e.clientHeight), 844, 'Mobile video fills viewport height');
        assert.equal(await viewport.evaluate(e => e.scrollHeight > e.clientHeight), true, 'Reels are physically stacked');
        assert.equal(await video().evaluate(e => e.loop), true, 'Reel loops');
        await page.locator('[data-video-mute]').click();
        assert.equal(await video().evaluate(e => e.muted), false, 'Speaker icon enables sound');
        const stage = await viewport.boundingBox();
        await page.mouse.click(stage.x + stage.width / 2, stage.y + stage.height / 2);
        assert.equal(await video().evaluate(e => e.paused), true, 'Tap pauses reel');
        await page.mouse.click(stage.x + stage.width / 2, stage.y + stage.height / 2);
        await page.waitForFunction(() => !document.querySelector('[data-player-slide].is-active video').paused);
        await page.mouse.move(stage.x + stage.width / 2, stage.y + stage.height / 2);
        await page.mouse.down();
        await page.waitForTimeout(300);
        assert.equal(await video().evaluate(e => e.paused), true, 'Hold pauses reel');
        await page.mouse.up();
        await page.waitForFunction(() => !document.querySelector('[data-player-slide].is-active video').paused);
        await viewport.evaluate(e => e.scrollTo({ top: e.clientHeight, behavior: 'instant' }));
        await page.waitForFunction(() => document.querySelector('[data-player-slide].is-active')?.dataset.index === '1');
        assert.equal(await page.locator('[data-player-slide] video').evaluateAll(es => es.filter(v => !v.paused).length), 1, 'Only active video plays');
        await page.waitForFunction(() => document.querySelector('[data-player-slide] video').currentTime < .1 && document.querySelector('[data-player-slide]').classList.contains('has-frame'));

        await page.keyboard.press('Escape');
        await page.waitForFunction(() => !document.querySelector('[data-video-player]').open);
        assert.equal(await dialog.locator('video').count(), 0, 'Closing releases video elements');
        await page.locator('[data-video-collection="stories"] [data-video-open]').first().click();
        await page.waitForFunction(() => document.querySelector('[data-player-slide].is-active video')?.currentTime > 0);
        assert.equal(await page.locator('[data-video-progress]').isVisible(), true, 'Stories show segments');
        assert.equal(await viewport.evaluate(e => e.scrollWidth > e.clientWidth), true, 'Stories are horizontal slides');
        assert.equal(await video().evaluate(e => e.loop), false, 'Stories continue to next');
        await page.mouse.click(stage.x + stage.width * .85, stage.y + stage.height / 2);
        await page.waitForFunction(() => document.querySelector('[data-player-slide].is-active')?.dataset.index === '1');
        await page.mouse.click(stage.x + stage.width * .15, stage.y + stage.height / 2);
        await page.waitForFunction(() => document.querySelector('[data-player-slide].is-active')?.dataset.index === '0');
        await page.mouse.move(stage.x + stage.width / 2, stage.y + stage.height / 2);
        await page.mouse.down();
        await page.waitForTimeout(300);
        assert.equal(await video().evaluate(e => e.paused), true, 'Hold pauses story');
        await page.mouse.up();
        await page.waitForFunction(() => !document.querySelector('[data-player-slide].is-active video').paused);
        assert.equal(await page.locator('[data-player-slide].is-active').getAttribute('data-index'), '0', 'Hold does not skip story');
        const lastStoryIndex = String(await page.locator('[data-player-slide]').count() - 1);
        await viewport.evaluate(e => e.scrollTo({ left: e.scrollWidth, behavior: 'instant' }));
        await page.waitForFunction(last => document.querySelector('[data-player-slide].is-active')?.dataset.index === last, lastStoryIndex);
        await page.waitForFunction(() => document.querySelector('[data-player-slide].is-active video').duration > 0);
        await video().evaluate(e => { e.currentTime = e.duration - .1; });
        await page.waitForFunction(() => !document.querySelector('[data-video-player]').open);
        await page.setViewportSize({ width: 1440, height: 1000 });
        await page.locator('[data-video-collection="reels"] [data-video-open]').first().click();
        assert.equal(await viewport.evaluate(e => e.clientHeight), 1000, 'Desktop video fills window height');
        await page.mouse.click(10, 500);
        await page.waitForFunction(() => !document.querySelector('[data-video-player]').open);
        console.log(`${browserType.name()} player interactions passed`);
    } finally {
        await browser.close();
    }
})().catch(error => { console.error(error); process.exitCode = 1; });
